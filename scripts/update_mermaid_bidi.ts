/** Reproduce optional Mermaid glyph data from the pinned Unicode 17 source; --check never uses the network. */
const root = new URL("../", import.meta.url);
const fixture = new URL("tests/fixtures/unicode/BidiMirroring-17.0.0.txt", root);
const output = new URL("src/content/mermaid_bidi_data.ts", root);
const sha256 = "a2f16fb873ab4fcdf3221cb1a8a85a134ddd6ed03603181823ff5206af3741ce";
const sourceIndex = Deno.args.indexOf("--source");
const source = await Deno.readTextFile(sourceIndex < 0 ? fixture : Deno.args[sourceIndex + 1]!);
if (source.length > 100_000) throw new RangeError("Unicode mirroring source exceeds its byte budget.");
const digest = [...new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(source)))].map((
  byte,
) => byte.toString(16).padStart(2, "0")).join("");
if (digest !== sha256) throw new Error("Unicode 17 mirroring source hash changed.");
const pairs = [...source.matchAll(/^([0-9A-F]{4,6}); ([0-9A-F]{4,6})/gm)].map((
  match,
) => [parseInt(match[1]!, 16), parseInt(match[2]!, 16)]);
const unpaired = [...source.matchAll(/^# ([0-9A-F]{4,6});/gm)].map((match) => parseInt(match[1]!, 16));
if (!pairs.length || !unpaired.length || pairs.length > 2048 || unpaired.length > 2048) {
  throw new Error("Invalid Unicode mirroring source counts.");
}
const hex = (point: number) => `0x${point.toString(16).toUpperCase().padStart(4, "0")}`;
const generated = "// Generated by scripts/update_mermaid_bidi.ts. Do not edit.\n" +
  "// Unicode 17.0.0 Bidi_Mirroring_Glyph; © 2025 Unicode, Inc.\n" +
  "// Source: https://www.unicode.org/Public/17.0.0/ucd/BidiMirroring.txt\n" +
  `// SHA-256: ${sha256}\n` +
  "// License: https://www.unicode.org/license.txt\n\n" +
  "/** Paired glyph substitutions, not bidi levels or a shaping algorithm. */\n" +
  `export const BIDI_MIRROR_PAIRS: readonly (readonly [number, number])[] = [\n${
    pairs.map(([a, b]) => `  [${hex(a!)}, ${hex(b!)}],`).join("\n")
  }\n];\n\n` +
  "/** Mirrored characters for which Unicode supplies no character-based glyph substitute. */\n" +
  `export const BIDI_MIRROR_UNPAIRED: readonly number[] = [\n${
    unpaired.map((point) => `  ${hex(point)},`).join("\n")
  }\n];\n`;
if (Deno.args.includes("--check")) {
  if (await Deno.readTextFile(output) !== generated) throw new Error("Unicode mirroring module is stale.");
} else {
  await Deno.writeTextFile(fixture, source);
  await Deno.writeTextFile(output, generated);
}
console.log(
  JSON.stringify({
    version: "17.0.0",
    sha256,
    pairs: pairs.length,
    unpaired: unpaired.length,
    checked: Deno.args.includes("--check"),
  }),
);
